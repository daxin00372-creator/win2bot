ALLOWED_USERS = [8046911093, 7719733958, 7029265940]
TOTAL_COUNT = len(TARGET_GROUPS)

async def handle_incoming_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not update.message:
        return

    message = update.message
    sender_id = message.from_user.id
    source_chat_id = message.chat_id

    if sender_id not in ALLOWED_USERS:
        logging.warning(f"Unauthorized access attempt by User ID: {sender_id}")
        return

    logging.info(f"Starting broadcast of message {message.message_id} to {TOTAL_COUNT} targets...")

    for index, group_id in enumerate(TARGET_GROUPS, start=1):
        if group_id == source_chat_id:
            continue
            
        try:
            await context.bot.copy_message(
                chat_id=group_id,
                from_chat_id=source_chat_id,
                message_id=message.message_id
            )
            logging.info(f"[{index}/{TOTAL_COUNT}] Successfully copied message {message.message_id} to group {group_id}")
            await asyncio.sleep(random.uniform(0.5, 1.5))
            
        except Exception as e:
            logging.error(f"[{index}/{TOTAL_COUNT}] Failed sending to group {group_id}: {str(e)}")
            await asyncio.sleep(5)

    logging.info("Broadcast sequence finished successfully.")

def main():
    if not BOT_TOKEN:
        logging.error("BOT_TOKEN is missing! Check your environment variables.")
        return

    application = Application.builder().token(BOT_TOKEN).build()
    SOURCE_FILTER = filters.ChatType.PRIVATE | filters.Chat(-1004450914055)
    application.add_handler(MessageHandler(filters.ALL & SOURCE_FILTER, handle_incoming_message))

    print(f"Bot is running securely and loaded with {TOTAL_COUNT} targets... Press Ctrl+C to stop.")
    application.run_polling()

if __name__ == '__main__':
    main()